"""Generate Markdown and CSV reports from ASV benchmark results.

Reads the latest JSON results generated by ASV and formats them into
human-readable tables, saving them to the 'reports' directory.
"""

import json
import os
import pathlib
import sys
from collections import defaultdict
from typing import Any

from tabulate import tabulate

PROJECT_ROOT = pathlib.Path(__file__).resolve().parents[1]
RESULTS_DIR = PROJECT_ROOT / ".asv" / "results"
REPORTS_DIR = PROJECT_ROOT / "reports"


def find_latest_results() -> dict[str, Any]:
    """Find the most recent ASV results JSON file."""
    if not RESULTS_DIR.exists():
        print(f"Error: Results directory not found at {RESULTS_DIR}", file=sys.stderr)
        print("Run 'asv run' first.", file=sys.stderr)
        sys.exit(1)

    # ASV stores results under .asv/results/MACHINE/COMMIT.json
    # We want the most recently modified JSON file
    json_files = list(RESULTS_DIR.rglob("*.json"))
    # Filter out machine.json
    result_files = [f for f in json_files if f.name != "machine.json"]
    
    if not result_files:
        print("Error: No benchmark results found.", file=sys.stderr)
        sys.exit(1)

    latest_file = max(result_files, key=lambda p: p.stat().st_mtime)
    print(f"Reading results from: {latest_file.relative_to(PROJECT_ROOT)}")
    
    with open(latest_file) as f:
        return json.load(f)


def format_time(seconds: float | None) -> str:
    """Format time in seconds to human readable string."""
    if seconds is None or str(seconds) == "nan":
        return "N/A"
    
    if seconds < 0.001:
        return f"{seconds * 1_000_000:.1f} μs"
    elif seconds < 1.0:
        return f"{seconds * 1000:.1f} ms"
    else:
        return f"{seconds:.2f} s"


def format_memory(bytes_val: float | None) -> str:
    """Format memory in bytes to human readable string."""
    if bytes_val is None or str(bytes_val) == "nan":
        return "N/A"
        
    mb = bytes_val / (1024 * 1024)
    if mb > 1024:
        return f"{mb / 1024:.2f} GB"
    return f"{mb:.1f} MB"


def format_value(value: float | None, bench_type: str) -> str:
    """Format value based on benchmark type."""
    if value is None or str(value) == "nan":
        return "-"
        
    if bench_type.startswith("time_"):
        return format_time(value)
    elif bench_type.startswith("peakmem_"):
        return format_memory(value)
    elif bench_type.startswith("track_throughput"):
        if value > 1_000_000:
            return f"{value / 1_000_000:.1f}M/s"
        elif value > 1_000:
            return f"{value / 1_000:.1f}K/s"
        return f"{value:.0f}/s"
    elif bench_type.startswith("track_speedup"):
        return f"{value:.1f}x"
    else:
        # Default numeric format
        if isinstance(value, float):
            return f"{value:.2f}"
        return str(value)


def generate_reports() -> None:
    """Generate Markdown and CSV reports."""
    REPORTS_DIR.mkdir(exist_ok=True)
    results = find_latest_results()
    
    # Restructure data: bench_name -> {param_combo -> result_value}
    # ASV stores results as a dict where keys are benchmark names
    # and values are dicts containing 'params' and 'result'
    
    reports_md = ["# FreshData Benchmark Results\n\n"]
    
    # Group benchmarks by file (e.g. benchmark_missing)
    bench_groups = defaultdict(dict)
    
    for bench_name, bench_data in results.get("results", {}).items():
        if not isinstance(bench_data, dict) or "result" not in bench_data:
            continue
            
        parts = bench_name.split(".")
        if len(parts) < 3:
            continue
            
        group_name = parts[-2]  # e.g., BenchmarkMissing
        method_name = parts[-1] # e.g., time_drop_missing
        
        bench_groups[group_name][method_name] = bench_data

    # Generate a table for each group
    for group_name, methods in sorted(bench_groups.items()):
        reports_md.append(f"## {group_name}\n")
        
        for method_name, data in sorted(methods.items()):
            reports_md.append(f"### `{method_name}`\n")
            
            param_names = data.get("params", [])
            # Skip non-parameterized or oddly parameterized methods for simple tables
            if not param_names or len(param_names) != 2:
                reports_md.append("_Requires 2 parameters (n_rows, library) for standard formatting._\n\n")
                continue
                
            # Usually: params = [["10000", "100000"], ["freshdata", "pandas", ...]]
            row_sizes = data.get("params")[0]
            libraries = data.get("params")[1]
            
            result_list = data.get("result", [])
            
            # ASV results list is flat, ordered by cartesian product of params
            headers = ["Library"] + [f"{size} rows" for size in row_sizes]
            table_data = []
            
            idx = 0
            for lib in libraries:
                row = [lib]
                for _ in row_sizes:
                    val = result_list[idx] if idx < len(result_list) else None
                    row.append(format_value(val, method_name))
                    idx += 1
                table_data.append(row)
                
            md_table = tabulate(table_data, headers=headers, tablefmt="github")
            reports_md.append(md_table + "\n\n")
            
    # Write Markdown report
    md_path = REPORTS_DIR / "summary.md"
    with open(md_path, "w") as f:
        f.write("".join(reports_md))
        
    print(f"Generated Markdown report: {md_path}")
    
    # Save raw structured data
    json_path = REPORTS_DIR / "results_extracted.json"
    with open(json_path, "w") as f:
        json.dump(bench_groups, f, indent=2)
        
    print(f"Generated JSON extract: {json_path}")


if __name__ == "__main__":
    generate_reports()
