"""CleanBench result reporting: JSON, markdown, and the docs site block."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "benchmarks" / "cleanbench" / "results"
DOCS_BENCHMARKS = REPO_ROOT / "docs" / "benchmarks.md"

_BLOCK_BEGIN = "<!-- cleanbench:begin (generated by benchmarks.cleanbench, do not edit) -->"
_BLOCK_END = "<!-- cleanbench:end -->"


def _fmt(value: Any) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.4f}"
    if value is None:
        return "—"
    return str(value)


def to_markdown(result: dict[str, Any]) -> str:
    lines = [
        "# CleanBench full-suite results",
        "",
        f"Generated: {datetime.now(timezone.utc).replace(microsecond=0).isoformat()}",
        f"Tracks: {', '.join(result['tracks_run'])} | "
        f"trained calib-v1 used: {_fmt(result.get('calibration_artifact_used'))}",
        f"Command: `{result.get('command', 'python -m benchmarks.cleanbench')}`",
        "",
    ]
    env = result.get("environment")
    if env:
        lines.append("## Environment")
        lines.append("")
        lines.append("| key | value |")
        lines.append("|---|---|")
        for key, value in env.items():
            lines.append(f"| {key} | {_fmt(value)} |")
        lines.append("")
    for track, values in result["tracks"].items():
        lines.append(f"## {track}")
        lines.append("")
        lines.append("| metric | value |")
        lines.append("|---|---|")
        for key, value in values.items():
            lines.append(f"| {key} | {_fmt(value)} |")
        lines.append("")
    baselines = result.get("baselines")
    if baselines:
        lines.append("## Baselines")
        lines.append("")
        lines.append("| baseline | status | detail |")
        lines.append("|---|---|---|")
        for name, values in baselines.items():
            status = values.get("status", "?")
            if status == "skipped":
                detail = values.get("reason", "")
            else:
                detail = ", ".join(
                    f"{k}={_fmt(v)}" for k, v in values.items()
                    if k not in ("baseline", "status")
                )
            lines.append(f"| {name} | {status} | {detail} |")
        lines.append("")
    gates = result["release_gates"]
    lines.append("## Release gates")
    lines.append("")
    if gates["passed"]:
        lines.append("**ALL GATES PASSED**")
    else:
        lines.append("**GATE FAILURES:**")
        lines.extend(f"- {failure}" for failure in gates["failures"])
    lines.append("")
    return "\n".join(lines)


def write_results(
    result: dict[str, Any], *, results_dir: Path | str = RESULTS_DIR
) -> tuple[Path, Path]:
    results_dir = Path(results_dir)
    results_dir.mkdir(parents=True, exist_ok=True)
    json_path = results_dir / "latest.json"
    json_path.write_text(json.dumps(result, indent=2, sort_keys=True, default=str) + "\n",
                         encoding="utf-8")
    md_path = results_dir / "latest.md"
    md_path.write_text(to_markdown(result), encoding="utf-8")
    return json_path, md_path


def update_docs_site(result: dict[str, Any], *, docs_path: Path | str = DOCS_BENCHMARKS) -> Path:
    """Refresh the marked CleanBench block inside docs/benchmarks.md."""
    docs_path = Path(docs_path)
    block = f"{_BLOCK_BEGIN}\n\n{to_markdown(result)}\n{_BLOCK_END}"
    if docs_path.is_file():
        text = docs_path.read_text(encoding="utf-8")
        if _BLOCK_BEGIN in text and _BLOCK_END in text:
            head, rest = text.split(_BLOCK_BEGIN, 1)
            _, tail = rest.split(_BLOCK_END, 1)
            text = head + block + tail
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
    else:
        text = block + "\n"
    docs_path.write_text(text, encoding="utf-8")
    return docs_path
